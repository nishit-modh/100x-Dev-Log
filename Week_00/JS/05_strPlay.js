// slice
let hello = "Hello World!"
console.log(hello.slice(0,4))
console.log(hello.slice(4,7))

// replace
hello = hello.replace("World", "Universe")
console.log(hello)

//  split
const str = "My name is XYZ."
const words = str.split(" ")
console.log(words)

// trim - extraplace in begining and end
let abc = "                  ABC xyz   " 
console.log(abc.trim())

// toUpper and toLower
console.log(abc.toUpperCase())
console.log(abc.toLowerCase())